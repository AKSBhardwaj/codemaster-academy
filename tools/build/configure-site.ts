import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export function deploymentSettings(
  publicUrl?: string,
  repository?: string,
): { siteUrl: string; baseHref: string } {
  let address = publicUrl?.trim();
  if (!address && repository) {
    const [owner, name, extra] = repository.split('/');
    if (!owner || !name || extra) throw new Error('GITHUB_REPOSITORY must be owner/repository.');
    address = `https://${owner.toLowerCase()}.github.io${name.toLowerCase() === `${owner.toLowerCase()}.github.io` ? '' : '/' + encodeURIComponent(name)}`;
  }
  const url = new URL(address || 'http://localhost:4200');
  if (
    !['https:', 'http:'].includes(url.protocol) ||
    url.username ||
    url.password ||
    url.search ||
    url.hash
  )
    throw new Error(
      'PUBLIC_SITE_URL must be an HTTP(S) site address without credentials, query or fragment.',
    );
  if (url.protocol !== 'https:' && !['localhost', '127.0.0.1', '[::1]'].includes(url.hostname))
    throw new Error('Use HTTPS for a public site.');
  const prefix = url.pathname.replace(/\/+$/, '');
  return { siteUrl: url.origin + prefix, baseHref: prefix + '/' };
}

export async function configureSite(local = false): Promise<ReturnType<typeof deploymentSettings>> {
  const settings = local
    ? deploymentSettings()
    : deploymentSettings(process.env['PUBLIC_SITE_URL'], process.env['GITHUB_REPOSITORY']);
  const file = resolve(import.meta.dirname, '../../src/content-schema/site-deployment.ts');
  await writeFile(
    file,
    `// Generated by tools/build/configure-site.ts. Set PUBLIC_SITE_URL to override.\nexport const DEPLOYMENT = ${JSON.stringify(settings, null, 2)} as const;\n`,
  );
  console.log(`[site] ${settings.siteUrl} (base ${settings.baseHref})`);
  return settings;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  configureSite(process.argv.includes('--local')).catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
