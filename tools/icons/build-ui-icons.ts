/**
 * Generates a tree-shakeable TypeScript map of the Bootstrap Icons used by the UI.
 * Only `<path>` based icons are supported so the Angular IconComponent can render
 * them from data without innerHTML. Run: npm run icons:build
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..', '..');
const ICON_DIR = resolve(ROOT, 'node_modules', 'bootstrap-icons', 'icons');
const LIST_FILE = resolve(import.meta.dirname, 'ui-icons.json');
const OUT_FILE = resolve(ROOT, 'src', 'app', 'shared', 'icons', 'ui-icons.generated.ts');

interface IconPath {
  d: string;
  fillRule?: string;
  clipRule?: string;
}

function parsePaths(name: string, svg: string): IconPath[] {
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const tags = inner.match(/<[a-zA-Z][^>]*>/g) ?? [];
  const paths: IconPath[] = [];
  for (const tag of tags) {
    if (!tag.startsWith('<path')) {
      throw new Error(`Icon "${name}" uses unsupported element ${tag.split(' ')[0]}>; pick a path-only icon.`);
    }
    const d = /\sd="([^"]+)"/.exec(tag)?.[1];
    if (!d) throw new Error(`Icon "${name}" has a <path> without a d attribute.`);
    const path: IconPath = { d };
    const fillRule = /fill-rule="([^"]+)"/.exec(tag)?.[1];
    const clipRule = /clip-rule="([^"]+)"/.exec(tag)?.[1];
    if (fillRule) path.fillRule = fillRule;
    if (clipRule) path.clipRule = clipRule;
    paths.push(path);
  }
  if (paths.length === 0) throw new Error(`Icon "${name}" contains no paths.`);
  return paths;
}

async function main(): Promise<void> {
  const names = JSON.parse(await readFile(LIST_FILE, 'utf8')) as string[];
  const unique = [...new Set(names)].sort();
  const entries: string[] = [];
  for (const name of unique) {
    const svg = await readFile(resolve(ICON_DIR, `${name}.svg`), 'utf8');
    const literal = parsePaths(name, svg)
      .map((p) => {
        const parts = [`d: ${JSON.stringify(p.d)}`];
        if (p.fillRule) parts.push(`fillRule: ${JSON.stringify(p.fillRule)}`);
        if (p.clipRule) parts.push(`clipRule: ${JSON.stringify(p.clipRule)}`);
        return `{ ${parts.join(', ')} }`;
      })
      .join(', ');
    entries.push(`  '${name}': [${literal}],`);
  }
  const union = unique.map((n) => `  | '${n}'`).join('\n');
  const out = `// AUTO-GENERATED by tools/icons/build-ui-icons.ts from Bootstrap Icons (MIT). Do not edit by hand.
export interface UiIconPath {
  readonly d: string;
  readonly fillRule?: string;
  readonly clipRule?: string;
}

export type UiIconName =
${union};

export const UI_ICONS: Readonly<Record<UiIconName, readonly UiIconPath[]>> = {
${entries.join('\n')}
};
`;
  await mkdir(resolve(OUT_FILE, '..'), { recursive: true });
  await writeFile(OUT_FILE, out, 'utf8');
  console.log(`[icons] wrote ${unique.length} UI icons -> ${OUT_FILE}`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
